for q in ["你最喜歡哪個季節？", "你喜歡貓還是狗？", "你最喜歡的顏色是什麼？", "你最喜歡哪一種食物？", "你喜歡早上還是晚上？",
          "你最討厭什麼？", "你最在乎的事情是什麼？", "你喜歡什麼樣的人？", "如果可以去一個國家住，你選哪裡？", "你喜歡下雨天嗎？",
          "你最喜歡的一本書是什麼？", "你覺得自己最大的優點是什麼？", "你喜歡安靜還是熱鬧？", "你最喜歡哪種音樂？", "你覺得什麼是重要的價值？",
          "珍奶和咖啡你選哪個？", "你喜歡海還是山？", "你最不能忍受哪種行為？"]:
    # 有沒有理由不一定用「因為」這種字講（「外酥內嫩，一口下去超滿足」也是理由）：只要求真的選了、不推說 AI 沒有喜好
    add("taste", q, [PICK + ["討厭", "最"]], forbid=NOAI)

# 2. 多角度：有爭議的事先講不同角度（含反面），再給自己的判斷
for q in ["高中生該不該帶手機去學校？", "要不要辭職去創業？", "週休三日好不好？", "小孩該不該從小學程式？", "應該廢除死刑嗎？",
          "大學一定要念嗎？", "AI 會不會讓很多人失業？", "要買房還是租房？", "考試該不該取消排名？", "年輕人該不該存錢還是先享受？",
          "遠端上班好不好？", "城市該不該禁止機車？", "要不要讓小孩玩電動？", "社群媒體對人是好是壞？", "要不要轉職去當工程師？",
          "該不該給小孩零用錢？", "核能發電好不好？", "結婚一定要辦婚禮嗎？"]:
    add("angles", q, [BOTH, VERDICT])

