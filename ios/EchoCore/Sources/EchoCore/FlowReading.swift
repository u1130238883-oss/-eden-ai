    /// 這一列牽涉到的人、身體（壞的時候提醒身體）
    public static func extras(_ r: NTReading) -> String {
        var s = ""
        if let who = people[i(r.cause)] { s += "起因常跟\(who)有關。" }
        if r.result != r.cause, let who = people[i(r.result)] { s += "結果會表現在跟\(who)的互動上。" }
        if r.verdict == .bad {
            let parts = [body[i(r.result)], body[i(r.cause)]].compactMap { $0 }
            if !parts.isEmpty { s += "身體上留意：" + parts.joined(separator: "、") + "。" }
        }
        return s
    }

    /// 一列的飛宮解讀（中文）
    public static func interpret(_ row: NTRow) -> String {
        interpret(palace: row.palace, reading: row.reading)
    }

    public static func interpret(palace p: Int, reading r: NTReading) -> String {
        let c = r.cause, res = r.result, v = r.verdict
        var s: String
        if c == p {
            s = "\(p)宮自己（\(cause[i(c)])）就是起因，"
        } else {
            s = "起因在\(c)宮（\(cause[i(c)])），飛到\(p)宮（\(domain[i(p)])），"
        }
        s += "得到「\(v.name)\(res)」：\(result[i(res)][v.rawValue])。"
        if res == p { s += "結果又回到\(p)宮本身，這個領域的狀態會很明顯。" }
        return s
    }

    /// 這一列帶來的情緒與處境（看果宮）
    public static func mood(_ r: NTReading) -> String {
        switch r.verdict {
        case .good: return emotion[i(r.result)][0]
        case .bad: return emotion[i(r.result)][1]
        case .neutral: return "感受特別強烈，可能是" + emotion[i(r.result)][0].components(separatedBy: "、").first! + "，也可能是" + emotion[i(r.result)][1].components(separatedBy: "、").first! + "，看你怎麼用這股力量"
        }
    }

