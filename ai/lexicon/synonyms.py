def groups():
    seen_group = set()
    out = []
    for line in GROUPS_TEXT.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        ws = []
        for w in line.split():
            if w not in ws:
                ws.append(w)
        if len(ws) >= 2 and tuple(ws) not in seen_group:
            seen_group.add(tuple(ws))
            out.append(ws)
    return out


if __name__ == "__main__":
    g = groups()
    words = {w for x in g for w in x}
