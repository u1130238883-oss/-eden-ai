def pairs():
    out = []
    seen = set()
    for line in PAIRS_TEXT.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        a, b = line.split()
        if a != b and (a, b) not in seen and (b, a) not in seen:
            seen.add((a, b))
            out.append((a, b))
    return out


