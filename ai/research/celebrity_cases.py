def year_facts(d, y):
    s, e, lp = d.luck_period(y)
    fy = d.year(y)
    aspects = d.luck_aspects(y)
    return {"luck": (s, e, lp), "flow": fy, "aspects": aspects,
            "triggered_aspects": d.triggered_aspects(y), "triggered_natal": d.triggered_natal(y)}


def touches(f, p):
    """這一年的大運、流年有沒有碰到 p 宮：走這一宮、或果／因是這一宮"""
    lp, fy = f["luck"][2], f["flow"]
    hits = []
    if lp.palace == p: hits.append("大運走這宮")
    if fy.palace == p: hits.append("流年走這宮")
    if p in (lp.reading.result, lp.reading.cause): hits.append("大運的果因是這宮")
    if p in (fy.reading.result, fy.reading.cause): hits.append("流年的果因是這宮")
    return hits


def verdict_for(f, p):
    """這一年 p 這一方面：大運十二方面的第 p 方面好正壞"""
    return VERDICTS[f["aspects"][p - 1].reading.verdict]


def main():
    random.seed(7)
    out_json = sys.argv[sys.argv.index("--json") + 1] if "--json" in sys.argv else None
    cases, lines = [], []
    hit_event = hit_base = n_event = n_base = 0
    vmatch = vtotal = vbase_match = vbase_total = 0
    for name, (by, bm, bd), events in PEOPLE:
        d = Destiny(by, bm, bd)
        natal = "、".join(r.text for r in d.natal)
        lines.append(f"\n## {name}（{by}-{bm:02d}-{bd:02d}）第{d.type}型「{TYPE_NAMES[d.type - 1]}」\n本命：{natal}")
        person = {"name": name, "birthday": [by, bm, bd], "type": d.type, "natal": [r.text for r in d.natal], "events": []}
        for y, what, p, sign in events:
            f = year_facts(d, y)
            h = touches(f, p)
            v = verdict_for(f, p)
            s, e, lp = f["luck"]
            lines.append(f"- {y} {what}（看 {p}宮{PALACE_NAMES[p - 1]}）：大運 {s}-{e} 走 {lp.text}，流年 {f['flow'].text}；"
                         f"第{p}方面{v}；{'、'.join(h) if h else '沒碰到這一宮'}")
            person["events"].append({"year": y, "event": what, "palace": p, "sign": sign, "luck": lp.text, "flow": f["flow"].text,
                                     "aspect": f["aspects"][p - 1].reading.text, "touch": h})
            n_event += 1
            hit_event += bool(h)
            # 好事對「好／正」、壞事對「壞」
            vtotal += 1
            vmatch += (sign == "+" and v != "壞") or (sign == "-" and v == "壞")
            # 對照組：同一個人、同一個宮位，隨便挑他 15～75 歲之間的其他年份
            for yb in random.sample([x for x in range(by + 15, by + 76) if abs(x - y) > 2], 5):
                fb = year_facts(d, yb)
                n_base += 1
                hit_base += bool(touches(fb, p))
                vb = verdict_for(fb, p)
                vbase_total += 1
                vbase_match += (sign == "+" and vb != "壞") or (sign == "-" and vb == "壞")
        cases.append(person)
    print("# 九型十二宮名人案例\n")
    print(f"事件年碰到對應宮位：{hit_event}/{n_event} = {hit_event / n_event:.0%}；隨機其他年份：{hit_base}/{n_base} = {hit_base / n_base:.0%}")
    print(f"那一方面的好壞跟事件好壞一致：{vmatch}/{vtotal} = {vmatch / vtotal:.0%}；隨機其他年份：{vbase_match}/{vbase_total} = {vbase_match / vbase_total:.0%}")
    print("\n".join(lines))
    if out_json:
        json.dump(cases, open(out_json, "w", encoding="utf-8"), ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()
