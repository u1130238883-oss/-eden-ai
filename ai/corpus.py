FALLBACK_USER = [
    "量子糾纏的數學推導", "幫我訂機票", "股票明天會漲嗎", "告訴我彩票號碼",
    "翻譯這段法文", "明天會發生什麼", "寫一篇論文", "幫我駭進系統",
    "宇宙的盡頭是什麼", "最新的新聞是什麼",
]
FALLBACK_REPLY = [
    "這個超出我的訊號範圍了，我只是個小模型，答不太出來。",
    "抱歉，這題我還不會。我們換個話題好嗎？",
    "這個我沒學過耶…要不要聊點別的？",
]

PREFIXES = ["", "", "", "", "欸，", "請問", "那個，", "嗯…", "NineSun，", "問你喔，", "喂，"]
SUFFIXES = ["", "", "", "", "？", "?", "！", "!", "啊", "呀", "嗎", "～", "。", "耶"]


def _noisy(s, rng):
    s2 = rng.choice(PREFIXES) + s + rng.choice(SUFFIXES)
    if rng.random() < 0.1:
        s2 = s2.upper() if s2.isascii() else s2
    return s2


def dialog_pairs(rng):
    out = []
    for users, replies in INTENTS:
        u = rng.choice(users)
        out.append((_noisy(u, rng), rng.choice(replies)))
    for _ in range(2):
        out.append((_noisy(rng.choice(FALLBACK_USER), rng), rng.choice(FALLBACK_REPLY)))
    return out


def all_chars():
    chars = set()
    for users, replies in INTENTS:
        for s in users + replies:
            chars.update(s)
            chars.update(s.upper())
    for s in FALLBACK_USER + FALLBACK_REPLY + PREFIXES + SUFFIXES:
        chars.update(s)
    return chars
