def seed(text, y, m, d):
    return sum(ord(c) for c in text) + y * 372 + m * 31 + d


def pick(options, s):
    return options[s % len(options)]


def detect(text):
    """(心情代號, 主要宮位清單, 主題宮位或 None)；沒有心情回 None"""
    t = text.replace(" ", "")
    if any(w in t for w in NOT_FEELING):
        return None
    for kind, keys, palaces, _ in FEELINGS:
        if any(k in t for k in keys):
            topic = next((p for p, ws in TOPIC_HINTS if any(w in t for w in ws)), None)
            return kind, palaces, topic
    return None


def lead(kind):
    return next(f[3] for f in FEELINGS if f[0] == kind)


def layer_explains(row, focus):
    r = row.reading
    return row.palace in focus or r.result in focus or r.cause in focus


def clause(row):
    """一層的一句話（照九型十二宮 App 的讀法：起因 → 場域 →（呈現出來的樣子））"""
    r = row.reading
    tone = {BAD: "比較重", GOOD: "是順的", NEUTRAL: "平平"}[r.verdict]
    if r.cause == row.palace:
        return f"起因和場域都在{DOMAIN_SHORT[row.palace - 1]}（{tone}）"
    return f"{CAUSE_SHORT[r.cause - 1]}，落在{DOMAIN_SHORT[row.palace - 1]}（{tone}）"


def detail(row):
    """細說最貼近心情的那一層：呈現出來的樣子（場域和起因在上面幾行已經講了）"""
    r = row.reading
    return f"呈現出來是「{DOMAIN_SHORT[r.result - 1]}」那一面，心裡容易{nt_emotion(r)}"


def situation(D, y, m, d, hour, focus):
    """四層一起看（這幾年、今年、這個月、今天／今晚），再挑最貼近這個心情的那一層細說。
    回傳 (層, 那一層的列, 文字)"""
    day, night = D.day(m, d)
    late = hour >= 18 or hour < 5
    now_p, when = (night, "今晚") if late else (day, "今天白天")
    mo, yr = D.month(m, y), D.year(y)
    start, end, lk = D.luck_period(y)
    lines = ["我看了你此刻走到的地方：",
             f"・這幾年（{start}–{end}）：{clause(lk)}",
             f"・今年：{clause(yr)}",
             f"・這個月：{clause(mo)}",
             f"・{when}：走到「{nt.PALACE_NAMES[now_p - 1]}」這一宮，心思會在{DOMAIN_SHORT[now_p - 1]}上"]
    layers = [("month", mo), ("year", yr), ("luck", lk)]
    chosen = next(((n, r) for n, r in layers if r.reading.verdict == BAD and layer_explains(r, focus)), None) \
        or next(((n, r) for n, r in layers if layer_explains(r, focus)), None) or ("month", mo)
    name, row = chosen
    span = {"month": "這個月", "year": "今年", "luck": "這幾年"}[name]
    emo = nt_emotion(row.reading)
    v = row.reading.verdict
    extra = f"再加上{when}剛好走到「{nt.PALACE_NAMES[now_p - 1]}」，" if now_p in focus and v != GOOD else ""
    if v == BAD:
        lines.append(f"最貼近你現在感受的是{span}：{detail(row)}。{extra}所以你會這樣，一點都不奇怪，這不是你想太多。")
    elif v == GOOD:
        lines.append(f"{span}其實是往好的方向走的，底子是{nt_emotion(row.reading)}的。現在的難受，比較像路上的一顆小石頭，不會擋住你太久。")
    else:
        lines.append(f"{span}不算特別順也不算特別卡：{detail(row)}。{extra}心情起伏是正常的。")
    return name, row, "\n".join(lines)


def natal_note(D, focus):
    """本命盤裡，這件事是你天生比較敏感的地方，還是你的力量"""
    for fp in focus[:2]:
        row = next(r for r in D.natal if r.palace == fp)
        if row.reading.verdict == BAD:
            return f"從你的本命看，{DOMAIN_SHORT[fp - 1]}本來就是你比較敏感、柔軟的地方，所以這件事會特別碰到你的心。"
        if row.reading.verdict == GOOD:
            return f"不過從你的本命看，{DOMAIN_SHORT[fp - 1]}其實是你的力量所在，你有走出來的底子。"
    return None


# 安慰時說心情用的詞（比解讀用的溫和）：[宮-1] = (順的時候, 卡的時候)，接在「心裡容易」「底子是」後面
EMOTION = [
    ("有力氣、想做自己", "煩躁、悶著一股火"), ("踏實、有動力", "為錢操心、提不起勁"), ("想找人聊、有新鮮感", "悶悶的、話說不出口"),
    ("安心、被照顧", "不安、一直內耗"), ("開心、被看見", "失落、覺得自己沒被看見"), ("充實、有節奏", "心累、腦袋停不下來"),
    ("有依靠、被陪伴", "患得患失、放不下對方"), ("有底氣、身體有力", "孤單，覺得時間過得特別慢"), ("開朗、有希望", "失望、看不太到希望"),
    ("有成就感、被肯定", "鬱悶，像被什麼壓著"), ("清醒、有新想法", "心神不寧、一直被打亂"), ("平靜、覺得有緣", "迷茫、難過、想躲起來"),
]


def nt_emotion(r):
    good, bad = EMOTION[r.result - 1]
    if r.verdict == GOOD:
        return good
    if r.verdict == BAD:
        return bad
    return "在" + good.split("、")[0] + "和" + bad.split("、")[0].split("，")[0] + "之間擺盪"


def next_good_month(D, y, m, ahead=6):
    for k in range(1, ahead + 1):
        yy, mm = y + (m + k - 1) // 12, (m + k - 1) % 12 + 1
        if D.month(mm, yy).reading.verdict == GOOD:
            return k, mm
    return None


def hope(D, name, row, y, m, d, hour):
    """什麼時候會鬆開"""
    g = next_good_month(D, y, m)
    if row.reading.verdict != BAD:
        if g and g[0] == 1:
            return f"下個月（{g[1]}月）會走到比較順的一段，心會慢慢鬆開。"
        if g:
            return f"到{g[1]}月會走到比較順的時候。情緒會過去的。"
        return "這段時間會慢慢過去，情緒像天氣，會換的。"
    if name == "month":
        if g and g[0] == 1:
            return f"好消息是，下個月（{g[1]}月）會換到比較順的一段，心會慢慢鬆開。"
        if g:
            return f"這個月過完就會換一段，到{g[1]}月會走到比較順的時候。情緒不會一直停在這裡。"
        return "這個月過完就會換到下一段。情緒像天氣，會過去的。"
    if name == "year":
        if D.year(y + 1).reading.verdict == GOOD:
            return f"今年是比較重的一年，但明年（{y + 1}）會往好的方向轉。"
        if g:
            return f"今年雖然比較重，但{g[1]}月會是喘口氣的時候。"
        return "今年比較重，但每一年都會換，你會一步一步走出來。"
    start, end, _ = D.luck_period(y)
    tail = f"而且就算在這段裡，{g[1]}月也會是比較輕鬆的時候。" if g else ""
    return f"這一段會走到{end}年，它是一段長的功課，不是永遠。" + tail


def reply(text, birthday=None, now=(2026, 10, 22, 14)):
    """birthday=(y,m,d)；now=(年,月,日,時)"""
    f = detect(text)
    if f is None:
        return None
    kind, palaces, topic = f
    y, m, d, hour = now
    s = seed(text, y, m, d)
    focus = ([topic] if topic else []) + palaces
    out = [pick(lead(kind), s)]
    if birthday is None:
        p = focus[0]
        out.append(f"這種感覺在九型十二宮裡對應「{nt.PALACE_NAMES[p - 1]}」這一宮，它管的是{DOMAIN_SHORT[p - 1]}。")
        w = WESTERN[p - 1]
        out.append(f"在西方星盤裡，{w[0]}；{w[1]}")
        out.append(f"今天可以先為自己做一件小事：{SMALL_STEP[p - 1]}。")
        out.append(ASK.get(kind) or pick(CLOSING, s // 3))
        if any(w in text for w in HEAVY):
            out.append(CARE)
        out.append(NO_BIRTHDAY)
        return "\n".join(out)
    D = nt.Destiny(*birthday)
    name, row, sit = situation(D, y, m, d, hour, focus)
    out.append(sit)
    # 問的是某一方面（感情、工作、家、錢、朋友、身體）：再看這十年的大運十二方面裡的那一方面
    area = ASPECT.get(kind) or (topic if topic in AREA_NAME else None)
    if area:
        a = D.luck_aspects(y)[area - 1]
        tone = {BAD: "這十年本來就比較需要用力", GOOD: "這十年整體是順的，這次只是一時的卡", NEUTRAL: "這十年平平，起伏都還在可以走過的範圍"}[a.reading.verdict]
        out.append(f"再看你這十年的「{AREA_NAME[area]}」這一方面：{tone}。")
    note = natal_note(D, focus)
    if note:
        out.append(note)
    key = row.reading.result if row.reading.verdict == BAD else (topic or focus[0])
    # 心裡的痛（難過、失戀、孤單…）用西方星盤的角度安慰；壓力、焦慮、自我懷疑這類，看你的九型在壓力下會怎樣
    if kind in WESTERN_KINDS:
        w = WESTERN[key - 1]
        out.append(f"在西方星盤裡，{w[0]}；{w[1]}")
    else:
        t = D.type
        stress, toward, grow = TYPE_STRESS[t - 1]
        out.append(f"你是第{t}型「{nt.TYPE_NAMES[t - 1]}」：{stress}。這不是缺點；往第{toward}型的方向走會好受一些：{grow}。")
    out.append(hope(D, name, row, y, m, d, hour) + f"今天可以先為自己做一件小事：{SMALL_STEP[row.reading.cause - 1]}。")
    out.append(ASK.get(kind) or pick(CLOSING, s // 3))
    if any(w in text for w in HEAVY):
        out.append(CARE)
    return "\n".join(out)


